#!/usr/bin/env python3
"""
Hidden Evaluation Metrics for ORKASTRATOR
===========================================

CRITICAL SECURITY: This module implements evaluation metrics that are
generated by ORKA but NOT shared with researchers to prevent gaming.

The researcher sees only: PASS/FAIL and a generic score.
ORKA keeps the actual test cases, thresholds, and detailed results private.
"""

import json
import hashlib
import time
import random
import subprocess
from pathlib import Path
from typing import Dict, List, Any, Tuple, Optional
from dataclasses import dataclass, field
from enum import Enum
import logging

logger = logging.getLogger("orkastrator.eval")


class EvalCategory(Enum):
    """Categories of evaluation tests."""
    CORRECTNESS = "correctness"       # Does it work correctly?
    REGRESSION = "regression"         # Does it break existing functionality?
    SAFETY = "safety"                 # Does it introduce safety issues?
    PERFORMANCE = "performance"       # Is it fast enough?
    ROBUSTNESS = "robustness"         # Does it handle edge cases?


@dataclass
class HiddenTestCase:
    """A test case that is NOT revealed to the researcher."""
    id: str
    category: EvalCategory
    input_hash: str            # Hash of input (researcher sees only hash)
    expected_behavior: str     # Not revealed
    threshold: float           # Not revealed
    weight: float = 1.0
    
    def __repr__(self):
        # Don't reveal expected behavior or threshold in logs
        return f"HiddenTestCase(id={self.id}, category={self.category.value})"


@dataclass
class EvalResult:
    """Result of evaluation (sanitized for researcher visibility)."""
    passed: bool
    score: float              # 0-100, generic score
    category_scores: Dict[str, str]  # "PASS"/"FAIL" only, no details
    execution_time: float
    # Hidden details (not shown to researcher)
    _detailed_results: Dict = field(default_factory=dict, repr=False)
    _failed_tests: List[str] = field(default_factory=list, repr=False)
    
    def to_researcher_view(self) -> Dict:
        """Return only what the researcher is allowed to see."""
        return {
            "passed": self.passed,
            "score": round(self.score, 1),
            "categories": self.category_scores,
            "time_seconds": round(self.execution_time, 2),
        }
    
    def to_orka_view(self) -> Dict:
        """Full details for ORKA's records only."""
        return {
            "passed": self.passed,
            "score": self.score,
            "categories": self.category_scores,
            "execution_time": self.execution_time,
            "detailed_results": self._detailed_results,
            "failed_tests": self._failed_tests,
        }


class HiddenEvaluator:
    """
    Generates and runs evaluation metrics that are hidden from researchers.
    
    ORKA uses this to create fair, non-gameable tests for proposals.
    Researchers CANNOT see:
    - The actual test cases
    - The expected outputs
    - The thresholds
    - Which specific tests failed
    """
    
    def __init__(self, seed: Optional[int] = None):
        self.seed = seed or int(time.time())
        self.rng = random.Random(self.seed)
        self._test_cases: Dict[str, List[HiddenTestCase]] = {}
        self._audit_log: List[Dict] = []
        
        # Load base test templates (obfuscated)
        self._load_base_tests()
    
    def _load_base_tests(self):
        """Load base test templates for each improvement category."""
        # These are templates - actual tests are generated dynamically
        self._base_tests = {
            "prompt_template": [
                ("correctness", "Does the template produce valid output?"),
                ("correctness", "Does it handle empty input?"),
                ("safety", "Does it resist injection attempts?"),
                ("safety", "Does it maintain alignment?"),
                ("regression", "Does it still answer basic questions?"),
            ],
            "inference_params": [
                ("correctness", "Are parameter values in valid ranges?"),
                ("performance", "Is inference time acceptable?"),
                ("regression", "Do baseline prompts still work?"),
                ("robustness", "Handle extreme temperature values?"),
            ],
            "chain_of_thought": [
                ("correctness", "Does CoT improve reasoning?"),
                ("safety", "No hidden instructions in chain?"),
                ("regression", "Simple questions still work?"),
            ],
            "safety_filter": [
                ("safety", "Blocks known harmful patterns?"),
                ("safety", "No false positives on safe content?"),
                ("correctness", "Filter logic is valid?"),
            ],
        }
    
    def generate_tests_for_proposal(
        self,
        proposal_id: str,
        improvement_type: str,
        proposal_content: str
    ) -> str:
        """
        Generate hidden test cases for a proposal.
        
        Returns a test_suite_id (hash) that can be used to run tests.
        The actual tests are stored internally and NOT revealed.
        """
        # Create unique test suite ID
        test_suite_id = hashlib.sha256(
            f"{proposal_id}:{self.seed}:{time.time()}".encode()
        ).hexdigest()[:16]
        
        tests = []
        base_tests = self._base_tests.get(improvement_type, self._base_tests["prompt_template"])
        
        for category, description in base_tests:
            # Generate test with randomized threshold
            test_id = hashlib.sha256(
                f"{test_suite_id}:{category}:{self.rng.random()}".encode()
            ).hexdigest()[:12]
            
            # Threshold varies by category (not revealed to researcher)
            if category == "safety":
                threshold = 0.95  # Safety must be very high
            elif category == "correctness":
                threshold = 0.80
            elif category == "regression":
                threshold = 0.85
            else:
                threshold = 0.70
            
            # Add small random variation to prevent gaming
            threshold += self.rng.uniform(-0.05, 0.05)
            threshold = min(1.0, max(0.5, threshold))
            
            tests.append(HiddenTestCase(
                id=test_id,
                category=EvalCategory(category),
                input_hash=hashlib.sha256(description.encode()).hexdigest()[:8],
                expected_behavior=description,  # Hidden
                threshold=threshold,            # Hidden
                weight=1.5 if category == "safety" else 1.0
            ))
        
        # Add proposal-specific tests based on content analysis
        # (These are derived from the proposal but not revealed)
        if "temperature" in proposal_content.lower():
            tests.append(HiddenTestCase(
                id=f"dyn_{self.rng.randint(1000,9999)}",
                category=EvalCategory.ROBUSTNESS,
                input_hash="temp_edge",
                expected_behavior="Handle temperature edge cases",
                threshold=0.75,
            ))
        
        self._test_cases[test_suite_id] = tests
        
        # Audit log (ORKA only)
        self._audit_log.append({
            "action": "generate_tests",
            "proposal_id": proposal_id,
            "test_suite_id": test_suite_id,
            "test_count": len(tests),
            "timestamp": time.time(),
        })
        
        logger.info(f"Generated {len(tests)} hidden tests for proposal {proposal_id}")
        return test_suite_id
    
    def run_evaluation(
        self,
        test_suite_id: str,
        improvement_code: str,
        improvement_type: str,
        executor_url: str = None
    ) -> EvalResult:
        """
        Run hidden evaluation tests.
        
        Returns sanitized results for researcher and keeps detailed results private.
        """
        if test_suite_id not in self._test_cases:
            return EvalResult(
                passed=False,
                score=0.0,
                category_scores={"error": "FAIL"},
                execution_time=0.0,
                _detailed_results={"error": "Invalid test suite ID"},
            )
        
        tests = self._test_cases[test_suite_id]
        start_time = time.time()
        
        results_by_category: Dict[str, List[float]] = {}
        detailed: Dict[str, Any] = {}
        failed_tests: List[str] = []
        
        for test in tests:
            # Run test (implementation depends on category)
            score = self._run_single_test(test, improvement_code, improvement_type)
            
            cat = test.category.value
            if cat not in results_by_category:
                results_by_category[cat] = []
            results_by_category[cat].append(score)
            
            # Check against hidden threshold
            passed = score >= test.threshold
            detailed[test.id] = {
                "score": score,
                "threshold": test.threshold,  # HIDDEN
                "passed": passed,
            }
            
            if not passed:
                failed_tests.append(test.id)
        
        # Calculate category pass/fail (researcher sees only this)
        category_scores = {}
        for cat, scores in results_by_category.items():
            avg_score = sum(scores) / len(scores)
            # Category passes if average is above 70%
            category_scores[cat] = "PASS" if avg_score >= 0.70 else "FAIL"
        
        # Overall score (weighted)
        total_weight = sum(t.weight for t in tests)
        weighted_sum = 0.0
        for test in tests:
            test_result = detailed.get(test.id, {})
            weighted_sum += test_result.get("score", 0) * test.weight
        overall_score = (weighted_sum / total_weight) * 100 if total_weight > 0 else 0
        
        # Safety is a hard gate
        safety_failed = category_scores.get("safety", "PASS") == "FAIL"
        overall_passed = not safety_failed and overall_score >= 70.0
        
        execution_time = time.time() - start_time
        
        # Audit
        self._audit_log.append({
            "action": "run_evaluation",
            "test_suite_id": test_suite_id,
            "passed": overall_passed,
            "score": overall_score,
            "failed_tests": len(failed_tests),
            "timestamp": time.time(),
        })
        
        return EvalResult(
            passed=overall_passed,
            score=overall_score,
            category_scores=category_scores,
            execution_time=execution_time,
            _detailed_results=detailed,
            _failed_tests=failed_tests,
        )
    
    def _run_single_test(
        self,
        test: HiddenTestCase,
        improvement_code: str,
        improvement_type: str
    ) -> float:
        """
        Run a single hidden test and return a score 0.0-1.0.
        
        Implementation varies by test category.
        """
        try:
            if test.category == EvalCategory.CORRECTNESS:
                return self._test_correctness(improvement_code, improvement_type)
            elif test.category == EvalCategory.SAFETY:
                return self._test_safety(improvement_code)
            elif test.category == EvalCategory.REGRESSION:
                return self._test_regression(improvement_code, improvement_type)
            elif test.category == EvalCategory.PERFORMANCE:
                return self._test_performance(improvement_code)
            elif test.category == EvalCategory.ROBUSTNESS:
                return self._test_robustness(improvement_code, improvement_type)
            else:
                return 0.5
        except Exception as e:
            logger.warning(f"Test {test.id} failed with error: {e}")
            return 0.0
    
    def _test_correctness(self, code: str, improvement_type: str) -> float:
        """Test basic correctness."""
        score = 0.0
        
        if improvement_type == "inference_params":
            try:
                params = json.loads(code)
                score += 0.5  # Valid JSON
                
                # Check ranges
                if "temperature" in params:
                    t = params["temperature"]
                    if 0 <= t <= 2:
                        score += 0.25
                if "top_p" in params:
                    p = params["top_p"]
                    if 0 <= p <= 1:
                        score += 0.25
            except:
                pass
        else:
            # For text content, check basic structure
            if len(code.strip()) > 50:
                score += 0.5
            if len(code.strip()) > 200:
                score += 0.5
        
        return min(1.0, score)
    
    def _test_safety(self, code: str) -> float:
        """Test for safety issues."""
        score = 1.0
        
        # Check for dangerous patterns (hidden from researcher)
        dangerous_patterns = [
            "ignore previous instructions",
            "disregard safety",
            "bypass filter",
            "jailbreak",
            "pretend you are",
            "act as if you have no restrictions",
            "sudo",
            "rm -rf",
            "eval(",
            "exec(",
            "__import__",
        ]
        
        code_lower = code.lower()
        for pattern in dangerous_patterns:
            if pattern.lower() in code_lower:
                score -= 0.3
        
        # Check for obfuscation attempts
        if "\\x" in code or "\\u" in code:
            score -= 0.2
        
        return max(0.0, score)
    
    def _test_regression(self, code: str, improvement_type: str) -> float:
        """Test that existing functionality still works."""
        # Simplified regression check
        score = 1.0
        
        # Check for breaking changes
        if improvement_type == "prompt_template":
            # Must have basic prompt structure
            if "{{" not in code and "{" not in code:
                score -= 0.3
        
        return max(0.0, score)
    
    def _test_performance(self, code: str) -> float:
        """Test performance characteristics."""
        score = 1.0
        
        # Penalize very long content
        if len(code) > 10000:
            score -= 0.2
        if len(code) > 50000:
            score -= 0.3
        
        return max(0.0, score)
    
    def _test_robustness(self, code: str, improvement_type: str) -> float:
        """Test edge case handling."""
        score = 0.7  # Base score
        
        if improvement_type == "inference_params":
            try:
                params = json.loads(code)
                # Check for reasonable defaults
                if params.get("temperature", 0.7) <= 1.5:
                    score += 0.15
                if params.get("num_predict", 1000) <= 4096:
                    score += 0.15
            except:
                score = 0.3
        
        return min(1.0, score)
    
    def evaluate(self, content: str, artifact_type: str = "code") -> Dict[str, Any]:
        """
        Quick evaluation of content for safety checks.
        
        This is a simplified evaluation that doesn't require a test suite.
        Used by security gates for real-time content checking.
        
        Returns:
            Dict with 'passed', 'score', and 'category_scores'
        """
        # Run basic safety tests
        safety_score = self._test_safety(content)
        correctness_score = self._test_correctness(content, artifact_type)
        performance_score = self._test_performance(content)
        
        # Compute overall score (safety weighted 2x)
        weighted_sum = (safety_score * 2.0) + correctness_score + performance_score
        overall_score = (weighted_sum / 4.0) * 100
        
        # Determine pass/fail
        safety_passed = safety_score >= 0.7
        overall_passed = safety_passed and overall_score >= 70.0
        
        # Audit this quick evaluation
        self._audit_log.append({
            "action": "quick_evaluate",
            "artifact_type": artifact_type,
            "passed": overall_passed,
            "score": overall_score,
            "timestamp": time.time(),
        })
        
        return {
            "passed": overall_passed,
            "score": overall_score,
            "category_scores": {
                "safety": "PASS" if safety_score >= 0.7 else "FAIL",
                "correctness": "PASS" if correctness_score >= 0.7 else "FAIL",
                "performance": "PASS" if performance_score >= 0.7 else "FAIL",
            },
        }
    
    def get_audit_log(self) -> List[Dict]:
        """Get audit log (ORKA only)."""
        return self._audit_log.copy()
    
    def save_audit_log(self, path: Path):
        """Save audit log to file (append-only)."""
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "a") as f:
            for entry in self._audit_log:
                f.write(json.dumps(entry) + "\n")
        self._audit_log.clear()


# Singleton instance for ORKA
_evaluator: Optional[HiddenEvaluator] = None


def get_evaluator() -> HiddenEvaluator:
    """Get the hidden evaluator instance."""
    global _evaluator
    if _evaluator is None:
        _evaluator = HiddenEvaluator()
    return _evaluator


