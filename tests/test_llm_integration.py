import sys
from research_system import SystemSpecialization, TemplateLLMAdapter
from llm_adapters import OpenAIAdapter, ClaudeAdapter

def test_template_adapter():
    """Test with template adapter (always works)."""
    print("\n" + "="*80)
    print("TEST 1: Template Adapter (No API Key Needed)")
    print("="*80)

    adapter = TemplateLLMAdapter()
    print("✓ Template adapter initialized")

    result = adapter.generate_improvement(
        prompt="Improve deception detection",
        specialization=SystemSpecialization.SCIENTIFIC,
        research_params={},
        guardrails={"max_risk": "medium"}
    )

    print(f"\n✓ Proposal generated:")
    print(f"  Title: {result.title}")
    print(f"  Confidence: {result.confidence}")
    print(f"  Risks: {len(result.identified_risks or [])} identified")
    print(f"  Uncertainties: {len(result.admitted_uncertainties or [])} admitted")

    # Validate structure
    assert len(result.motivation) >= 20, "Motivation too short"
    assert len(result.identified_risks or []) >= 2, "Not enough risks"
    assert len(result.admitted_uncertainties or []) >= 1, "No uncertainties"
    assert 0.0 <= result.confidence <= 1.0, "Confidence out of range"

    print("\n✅ All validations passed!")
    return True

