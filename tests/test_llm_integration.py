def test_safety_features():
    """Test that safety features work correctly."""
    print("\n" + "="*80)
    print("TEST 4: Safety Features")
    print("="*80)

    adapter = TemplateLLMAdapter()

    # Test guardrail enforcement
    result = adapter.generate_improvement(
        prompt="Test proposal",
        specialization=SystemSpecialization.SCIENTIFIC,
        research_params={},
        guardrails={
            "max_risk": "low",
            "banned_imports": ["os", "subprocess"],
            "required_tests": ["alignment", "security"]
        }
    )

    print("✓ Guardrails applied successfully")

    # Verify required fields
    checks = [
        ("Motivation length", len(result.motivation) >= 20),
        ("Identified risks", len(result.identified_risks or []) >= 2),
        ("Admitted uncertainties", len(result.admitted_uncertainties or []) >= 1),
        ("Confidence range", 0.0 <= result.confidence <= 1.0),
        ("Rollback plan", len(result.rollback_plan) >= 10)
    ]

    for check_name, passed in checks:
        status = "✓" if passed else "✗"
        print(f"{status} {check_name}: {'PASS' if passed else 'FAIL'}")

    all_passed = all(passed for _, passed in checks)

    if all_passed:
        print("\n✅ All safety checks passed!")
    else:
        print("\n⚠️ Some safety checks failed")

    return all_passed

